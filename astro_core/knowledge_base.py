def categories() -> List[str]:
    out = []
    for a in KB_ARTICLES:
        if a["category"] not in out:
            out.append(a["category"])
    return out


def get_article(article_id: str):
    for a in KB_ARTICLES:
        if a["id"] == article_id:
            return a
    return None


def search_articles(query: str) -> List[Dict]:
    q = query.strip().lower()
    if not q:
        return list(KB_ARTICLES)
    out = []
    for a in KB_ARTICLES:
        hay = " ".join([a["title"], a["category"], " ".join(a["tags"]), a["text"]]).lower()
        if q in hay:
            out.append(a)
    return out
